       }
     }
     if(trim($this->y04_msgretorno)!="" || isset($GLOBALS["HTTP_POST_VARS"]["y04_msgretorno"])){
       $sql  .= $virgula." y04_msgretorno = '$this->y04_msgretorno' ";
       $virgula = ",";
