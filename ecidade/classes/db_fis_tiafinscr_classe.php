public function sql_query ( $y94_codtiaf=null,$campos="*",$ordem=null,$dbwhere=""){
     $sql = "select ";
     if($campos != "*" ){
       $campos_sql = explode("#",$campos);
       $virgula = "";
       for($i=0;$i<sizeof($campos_sql);$i++){
         $sql .= $virgula.$campos_sql[$i];
         $virgula = ",";
       }
     }else{
       $sql .= $campos;
     }
     $sql .= " from fiscalizacao.fis_tiafinscr ";
     $sql .= "      inner join issbase  on  issbase.q02_inscr = fis_tiafinscr.y94_inscr";
     $sql .= "      inner join fiscalizacao.fis_tiaf  on  fis_tiaf.y90_codtiaf = fis_tiafinscr.y94_codtiaf";
     $sql .= "      inner join cgm  on  cgm.z01_numcgm = issbase.q02_numcgm";
     $sql2 = "";
     if($dbwhere==""){
       if($y94_codtiaf!=null ){
         $sql2 .= " where fis_tiafinscr.y94_codtiaf = $y94_codtiaf ";
       }
     }else if($dbwhere != ""){
       $sql2 = " where $dbwhere";
     }
     $sql .= $sql2;
     if($ordem != null ){
       $sql .= " order by ";
       $campos_sql = explode("#",$ordem);
       $virgula = "";
       for($i=0;$i<sizeof($campos_sql);$i++){
         $sql .= $virgula.$campos_sql[$i];
         $virgula = ",";
       }
     }
     return $sql;
  }
