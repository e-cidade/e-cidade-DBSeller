public function sql_query ( $y95_codtiaf=null,$campos="*",$ordem=null,$dbwhere=""){
     $sql = "select ";
     if($campos != "*" ){
       $campos_sql = explode("#",$campos);
       $virgula = "";
       for($i=0;$i<sizeof($campos_sql);$i++){
         $sql .= $virgula.$campos_sql[$i];
         $virgula = ",";
       }
     }else{
       $sql .= $campos;
     }
     $sql .= " from fiscalizacao.fis_tiafcgm ";
     $sql .= "      inner join cgm  on  cgm.z01_numcgm = fis_tiafcgm.y95_numcgm";
     $sql .= "      inner join fiscalizacao.fis_tiaf  on  fis_tiaf.y90_codtiaf = fis_tiafcgm.y95_codtiaf";
     $sql2 = "";
     if($dbwhere==""){
       if($y95_codtiaf!=null ){
         $sql2 .= " where fis_tiafcgm.y95_codtiaf = $y95_codtiaf ";
       }
     }else if($dbwhere != ""){
       $sql2 = " where $dbwhere";
     }
     $sql .= $sql2;
     if($ordem != null ){
       $sql .= " order by ";
       $campos_sql = explode("#",$ordem);
       $virgula = "";
       for($i=0;$i<sizeof($campos_sql);$i++){
         $sql .= $virgula.$campos_sql[$i];
         $virgula = ",";
       }
     }
     return $sql;
  }
