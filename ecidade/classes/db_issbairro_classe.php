       $this->erro_status = "0";
       return false;
     }
       $this->q13_inscr = $q13_inscr;
     if(($this->q13_inscr == null) || ($this->q13_inscr == "") ){
       $this->erro_sql = " Campo q13_inscr nao declarado.";
