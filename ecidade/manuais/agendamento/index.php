</P>
<H2 CLASS="western" ALIGN=JUSTIFY STYLE="page-break-after: avoid"><A NAME="1.1.CGS &ndash; Cadastro Geral de Sa&uacute;de|outline"></A>
<FONT COLOR="#000080"><FONT FACE="Helvetica"><FONT SIZE=4><I><U><B><A HREF="#Sum&aacute;rio1_Head|region" NAME="db1045399db">CGS
&ndash; Cadastro Geral de Sa&uacute;de</A></B></U></I></FONT></FONT></FONT></H2>
<P CLASS="western" STYLE="text-indent: 2cm; margin-bottom: 0cm"><A HREF="#Sum&aacute;rio1|region" NAME="db6886db"><FONT COLOR="#000000"><SPAN STYLE="font-style: normal">	Este
cadastro consiste an criar uma base de dados dos pacientes de todo o
munic&iacute;pio, permitindo interligar todas as unidades no mesmo
Cadastro Geral de Sa&uacute;de. O CGS &eacute; o cadstro mais
importante deste m&oacute;dulo e da &aacute;rea do sistema de sa&uacute;de,
pois todos os dados converte para o hist&oacute;rico de dados do
paciente. Para fazer inclus&otilde;es nesse cadastro, preencha os
seguintes campos:</SPAN></FONT></A></P>
<H3 CLASS="western"><A NAME="1.1.1.Inclus&atilde;o|outline"></A><A HREF="#Sum&aacute;rio1_Head|region" NAME="db1045410db"><FONT SIZE=3><I><SPAN STYLE="text-decoration: none">Inclus&atilde;o</SPAN></I></FONT></A></H3>
<P CLASS="western" STYLE="text-indent: 2cm; margin-bottom: 0cm">ABA
Dados Pessoais</P>
<UL>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>CGS:
	</B></SPAN><SPAN STYLE="font-style: normal">Ser&aacute; gerado
	automaticamente e corresponde ao c&oacute;digo que est&aacute; sendo
	inclu&iacute;do;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>CGS
	do Munic&iacute;pio: </B></SPAN><SPAN STYLE="font-style: normal">Indica
	se o Paciente reside ou n&atilde;o no munic&iacute;pio;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>CPF:
	</B></SPAN><SPAN STYLE="font-style: normal">N&atilde;o &eacute;
	obrigat&oacute;rio, mas serve como campo de pesquisa para o CGS,
	ent&atilde;o &eacute; importante ser preenchido. Este campo tamb&eacute;m
	serve como chave no caso de cadastro duplicado de CGS, n&atilde;o
	permite cadastrar dois com o mesmo CPF;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Nome:</B></SPAN><SPAN STYLE="font-style: normal">
	&Eacute; cadastrado o nome do Paciente, permitindo sua identifia&ccedil;&atilde;o.
	Esse campo &eacute; obrigat&oacute;rio;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Pai:
	</B></SPAN><SPAN STYLE="font-style: normal">Nesse campo deve ser
	cadastrado o Pai do paciente, n&atilde;o sendo uma chave para
	inclus&atilde;o do CGS e n&atilde;o &eacute; obrigat&oacute;rio.</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>M&atilde;e:</B></SPAN><SPAN STYLE="font-style: normal">
	Nesse campo deve ser cadastrada a M&atilde;e do Paciente, sendo
	usada como uma chave para inclus&atilde;o do CGS junto com a data de
	nascimento, ent&atilde;o esse &eacute; um campo obrigat&oacute;rio
	no sistema;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Data
	de Nascimento:</B></SPAN><SPAN STYLE="font-style: normal"> Nesse
	campo deve ser cadastrada a data de nascimento do Paciente, que &eacute;
	campo obrigat&oacute;rio no sistema e chave conjunta com o nome da
	m&atilde;e para o CGS. Ent&atilde;o o sistema n&atilde;o permite
	cadastrar um CGS que possui o mesmo nome, nome da m&atilde;e e data
	de nascimento;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Sexo:</B></SPAN><SPAN STYLE="font-style: normal">
	Selecione o sexo do Paciente, que foi buscado os tipos do Governo do
	Minist&eacute;rio da Sa&uacute;de.</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Estado
	Civil:</B></SPAN><SPAN STYLE="font-style: normal"> Selecionar o
	estado civil do Paciente, que foi buscado os tipos do Governo do
	Minist&eacute;rio da Sa&uacute;de;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Cart&atilde;o
	SUS:</B></SPAN><SPAN STYLE="font-style: normal"> Neste campo &eacute;
	cadastrado n&uacute;mero do cart&atilde;o SUS que o Paciente recebe
	ao ser cadastrado no Cadastro de Sa&uacute;de do Governo, Esse
	n&uacute;mero &eacute; muito importante pois algumas rotinas poder&atilde;o
	ser feitas apenas se tiver cadastrado esse c&oacute;digo;</SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Endere&ccedil;o
	Pessoal:</B></SPAN><SPAN STYLE="font-style: normal"> Neste campo
	deve ser preechido o endere&ccedil;o residencial do Paciente, que
	serve para identificar se o mesmo reside no munic&iacute;pio ou n&atilde;o.
	Caso o Paciente n&atilde;o perten&ccedil;a ao Programa de Sa&uacute;de
	da Fam&iacute;lia (PSF), n&atilde;o tem endere&ccedil;o no
	munic&iacute;pio.</SPAN></P>
	<P CLASS="western" STYLE="margin-bottom: 0cm; font-style: normal"><IMG SRC="Manual_Agendamento_html_m41e1a7e1.png" NAME="graphics1" ALIGN=LEFT WIDTH=605 HEIGHT=337 BORDER=0></P>
</UL>
<P CLASS="western" STYLE="text-indent: 2cm; margin-bottom: 0cm"><BR>
