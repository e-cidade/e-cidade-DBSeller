<P CLASS="western" STYLE="text-indent: 2cm; margin-bottom: 0cm">ABA
Outros Dados</P>
<UL>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><B>Micro:</B>
	Selecionar a qual micro regi&atilde;o o paciente pertence no
	munic&iacute;pio, de acordo com o PSF (Programa de Sa&uacute;de da
	Fam&iacute;lia), em algumas Prefeituras os pacientes tem alguns
	benef&iacute;cios se estiverem vinculados ao Programa, por isso &eacute;
	uma informa&ccedil;&atilde;o importante no sistema.</P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><B>Fam&iacute;lia:
	</B>Para selecionar uma Fam&iacute;lia, precisa estar vinculada &agrave;
	uma micro regi&atilde;o, neste caso, estar no PSF. O sistema s&oacute;
	busca as Fam&iacute;lias que pertencem as micro regi&otilde;es
	selecionadas no campo acima;</P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><B>Fator RH:</B>
	cadastrar o Fator RH do Paciente, esta informa&ccedil;&atilde;o
	somente deve ser preenchida a partir de um exame ou carteirinha que
	comprove o fator sanguineo;</P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><B>Tipo Sanguineo:</B>
	Cadastrar o Tipo Sanguineo do Paciente, <SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">esta
	informa&ccedil;&atilde;o somente deve ser preenchida a partir de um
	exame ou carteirinha que comprove o fator sanguineo;</SPAN></SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Nome
	do Respons&aacute;vel:</B></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">
	Cadastrar o nome do respons&aacute;vel pelo Paciente, em caso de
	menor de idade ou portador de alguma defici&ecirc;ncia;</SPAN></SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Ra&ccedil;a:</B></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">
	Selecionar neste campo a ra&ccedil;a do Paciente, que foi buscado os
	tipos do Governo do Minist&eacute;rio da Sa&uacute;de;</SPAN></SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Bolsa
	Fam&iacute;lia:</B></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">
	Selecionar se o Paciente participa do programa Bolsa Fam&iacute;lia
	</SPAN></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">do
	Governo Federal, este cadastro vai permitir que estes CGSs ganhe
	alguns benef&iacute;cios no M&oacute;dulo de S&oacute;cio Econ&ocirc;mico.</SPAN></SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Observa&ccedil;&otilde;es:</B></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">
	Cadastrar algumas informa&ccedil;&otilde;es peculiares do CGS, no
	caso de alguns relat&oacute;rios do sistema de sa&uacute;de, sair&aacute;
	essas informa&ccedil;&otilde;es. Essas informa&ccedil;&otilde;es
	ser&atilde;o atualizadas pelo M&eacute;dico na consulta, pelo campo
	Fatores de Risco;</SPAN></SPAN></P>
	<LI><P CLASS="western" STYLE="margin-bottom: 0cm"><SPAN STYLE="font-style: normal"><B>Foto:</B></SPAN><SPAN STYLE="font-style: normal"><SPAN STYLE="font-weight: medium">
	Permite ser anexada a foto do Paciente para uma melhor
	identifoca&ccedil;&atilde;o.</SPAN></SPAN></P>
