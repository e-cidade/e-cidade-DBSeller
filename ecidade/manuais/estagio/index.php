utilizar, visto que pode haver mais de um est&aacute;gio cadastrado,
por exemplo pode haver pontua&ccedil;&atilde;o diferente ou quest&otilde;es
diferenciadas para professores e demais funcion&aacute;rios.</P>
<H3 CLASS="western" ALIGN=JUSTIFY><A NAME="1.1.1.Inclus&atilde;o|outline"></A>
<A HREF="#Sum&aacute;rio1|region" NAME="db442839db">Inclus&atilde;o</A></H3>
<P CLASS="western" ALIGN=JUSTIFY><I><B>Aba Est&aacute;gio</B></I></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Sequencial:
</B><SPAN STYLE="font-weight: medium">Campo preenchido
automaticamente pelo sistema.</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Lei:</B><SPAN STYLE="font-weight: medium">
Lei ou decreto que define como ser&aacute; o m&eacute;todo de
avali&ccedil;&atilde;o utilizado do est&aacute;gio probat&oacute;rio,
ou seja, qual a periodicidade da avalia&ccedil;&atilde;o, a pontu&ccedil;&atilde;o
dos quesitos, etc.</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Descri&ccedil;&atilde;o:</B><SPAN STYLE="font-weight: medium">
Descri&ccedil;&atilde;o da avalia&ccedil;&atilde;o.</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Observa&ccedil;&atilde;o:</B><SPAN STYLE="font-weight: medium">
Observa&ccedil;&atilde;o sobre o est&aacute;gio probat&oacute;rio,
pode ser utilizado para colocar as caracter&iacute;sticas de
avalia&ccedil;&atilde;o do est&aacute;gio.</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Conf.
Obs:</B><SPAN STYLE="font-weight: medium"> local onde configuramos
onde ser&aacute; digitado e impresso as observa&ccedil;&otilde;es das
avalia&ccedil;&otilde;es:</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm"><I><SPAN STYLE="font-weight: medium">Ambos:</SPAN></I><SPAN STYLE="font-weight: medium">
ser&aacute; solicitado uma observa&ccedil;&atilde;o a cada quest&atilde;o
do est&aacute;gio e tamb&eacute;m no quesito;</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm; font-weight: medium">
Pergunta: o observa&ccedil;&atilde;o ser&aacute; digitada e impressa
somente na quest&atilde;o (pergunta);</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm; font-weight: medium">
Quesito: a observa&ccedil;&atilde;o ser&aacute; digitada e impressa
somente no quesito.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm; font-weight: medium">
<B>M&iacute;nimo de Pontos:</B> m&iacute;nimo de pontos para passar
autom&aacute;ticamente no est&aacute;gio probat&oacute;rio. O sistema
utilizar&aacute; o valor deste campo para saber se o servidor passou
ou n&atilde;o no est&aacute;gio probat&oacute;rio.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Portaria
Aprova&ccedil;&atilde;o:</B><SPAN STYLE="font-weight: medium"> qual &eacute;
o modelo de portaria que ser&aacute; impresso quando terminado o
est&aacute;gio probat&oacute;rio do funcion&aacute;rio desde que o
mesmo tenha passado.</SPAN></P>
