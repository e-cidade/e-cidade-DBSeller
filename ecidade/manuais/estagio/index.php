<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm"><B>Portaria
Reprova&ccedil;&atilde;o:</B><SPAN STYLE="font-weight: medium"> qual
o modelo de portaria que ser&aacute; impresso caso o servidor n&atilde;o
tenha passado no est&aacute;gio.</SPAN></P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 0.98cm; font-weight: medium">
