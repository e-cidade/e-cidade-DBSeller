<P CLASS="western" ALIGN=CENTER STYLE="margin-bottom: 0cm; page-break-before: always">
<FONT SIZE=4 STYLE="font-size: 16pt"><B>M&oacute;dulo Est&aacute;gio
Probat&oacute;rio</B></FONT></P>
<P CLASS="western" ALIGN=CENTER STYLE="margin-bottom: 0cm"><BR>
</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm">O
est&aacute;gio probat&oacute;rio &eacute; uma avalia&ccedil;&atilde;o
que o servidor de cargo efetivo se submete para verificar se ele
merece ou n&atilde;o se estabilizar no servi&ccedil;o p&uacute;blico.
Normalmente, ele &eacute; avaliado quanto a sua assiduidade,
pontualidade, responsabilidade, iniciativa para exercer as
atribui&ccedil;&otilde;es do cargo e etc..</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm">O
est&aacute;gio probat&oacute;rio e a estabilidade s&atilde;o
institutos jur&iacute;dicos distintos. A estabilidade &eacute; um
direito constitucional para quem possui cargo p&uacute;blico efetivo
(art. 41 da CR/88) e ser&aacute; adquirida ap&oacute;s 3 anos de
efetivo exerc&iacute;cio. A aprova&ccedil;&atilde;o no est&aacute;gio
probat&oacute;rio &eacute; um dos requisitos para aquisi&ccedil;&atilde;o
da estabilidade, n&atilde;o se confundindo os institutos.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm">Cabe
cada entidade federativa (Uni&atilde;o, Estados, Distrito Federal e
Munic&iacute;pios) legislar sobre o est&aacute;gio probat&oacute;rio
dos seus respectivos servidores por determina&ccedil;&atilde;o do
art. 18 da Constitui&ccedil;&atilde;o da Rep&uacute;blica, bem como,
como regra, qualquer assunto de mat&eacute;ria administrativa.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm">Assim, a
Uni&atilde;o pode estabelecer, atrav&eacute;s de lei, regras
administrativas diferentes dos Estados. Os Munic&iacute;pios podem
estabelecer regras distintas dos Estados, Distrito Federal ou Uni&atilde;o.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 1.98cm">Por
isso, o prazo de dura&ccedil;&atilde;o do est&aacute;gio probat&oacute;rio
pode variar de ente federativo para ente federativo. Por exemplo, na
Uni&atilde;o a dura&ccedil;&atilde;o do est&aacute;gio probat&oacute;rio
&eacute; de 2 (dois) anos, conforme disciplina o art. 20 da lei
8.112/90, e o est&aacute;gio probat&oacute;rio do pol&iacute;cia
civil do Rio de Janeiro &eacute; de 2 anos e 6 meses (art. 19 da lei
estadual 3.586/2001). Em rela&ccedil;&atilde;o &agrave; Uni&atilde;o
esse prazo &eacute; bastante discut&iacute;vel. A discuss&atilde;o
para pela id&eacute;ia do prazo ser de 2 anos ou 3 anos. O Superior
Tribunal de Justi&ccedil;a (STJ), reiteradamente, vem decidindo
corretamente que a dura&ccedil;&atilde;o do est&aacute;gio probat&oacute;rio
&eacute; de 2 anos na Uni&atilde;o, conforme previs&atilde;o do art.
20 da lei 8.112/90. Cabe ao STJ julgar em &uacute;ltima an&aacute;lise
no Brasil sobre esse prazo, por ser lei federal (art. 105, III, &quot;a&quot;
da CR/88).</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">Superada
essa etapa relativa &agrave; dura&ccedil;&atilde;o do est&aacute;gio
probat&oacute;rio, passo analisar os seus efeitos.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">O
servidor que n&atilde;o aprovado no est&aacute;gio probat&oacute;rio
dever&aacute; ser exonerado em decorr&ecirc;ncia do princ&iacute;pio
constitucional da efici&ecirc;ncia, caso ele demonstre inaptid&atilde;o
para exercer as atribui&ccedil;&otilde;es do cargo.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">Para que
essa exonera&ccedil;&atilde;o ocorra, dever&aacute; a Administra&ccedil;&atilde;o
P&uacute;blica, pouco importando se o servidor &eacute; federal,
distrital, estadual ou municipal, observar os seguintes requisitos:</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">1)
Contradit&oacute;rio e a ampla defesa, atrav&eacute;s de um processo
administrativo (art. 5&ordm;, LV da CR/88);</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">2)
princ&iacute;pio da motiva&ccedil;&atilde;o.</P>
<P CLASS="western" ALIGN=JUSTIFY STYLE="text-indent: 2.01cm">O
servidor que tiver uma avalia&ccedil;&atilde;o insatisfat&oacute;ria
no est&aacute;gio probat&oacute;rio n&atilde;o poder&aacute; ser
exonerado automaticamente. O mesmo tem o direito constitucional do
contradit&oacute;rio e da ampla defesa, atrav&eacute;s da exist&ecirc;ncia
de um processo administrativo. Tal direito visa afastar avalia&ccedil;&otilde;es
mentirosas e persegui&ccedil;&otilde;es funcionais e reduzir o
arb&iacute;trio da autoridade, sendo, portanto, o limite da
discricionariedade administrativa e o abuso de poder.</P>
